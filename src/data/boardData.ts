// Helper to get active question data for a cell given the current topic
export function getCellQuestion(cell: BoardCell, topic: MathTopic): QuestionData {
  if (cell.topicQuestions && cell.topicQuestions[topic]) {
    return cell.topicQuestions[topic];
  }
  
  // Fallback to original decimal compare
  const numA = cell.numA || '0';
  const numB = cell.numB || '0';
  const larger = cell.largerNum || numA;
  return {
    topic: 'decimal_compare',
    topicLabel: 'So sánh số thập phân',
    cellDisplay: `${numA} / ${numB}`,
    questionPrompt: 'Số nào LỚN HƠN trong hai số dưới đây?',
    options: [numA, numB],
    correctAnswer: larger,
    explanation: cell.explanation || `Số lớn hơn là ${larger}.`,
  };
}
